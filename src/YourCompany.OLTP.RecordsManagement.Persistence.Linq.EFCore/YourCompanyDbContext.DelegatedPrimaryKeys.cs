        public PropertyEntry<DelegatedPrimaryKeyGenerationTable, long>
            GeneratePrimaryKey<TRecordData, TQueryableRecordData>(PrimaryKey primaryKey)
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            if (primaryKey == null) throw new ArgumentNullException(nameof(primaryKey));
            EnsureLocked();

            Guid publicKey = primaryKey.CheckPublicKeyIsAssigned()
                ? primaryKey.PublicKey ?? throw new ApplicationException("!primaryKey.PublicKey.HasValue")
                : Guid.NewGuid();
            primaryKey.SetPublicKey(publicKey);
            if (!primaryKey.CheckPublicKeyIsAssigned()) throw new ApplicationException("!primaryKey.CheckPublicKeyIsAssigned()");

            var generatedPrivateKeyEntry = DelegatedPrimaryKeyGenerationTableSet<TRecordData, TQueryableRecordData>()
                .Add(new DelegatedPrimaryKeyGenerationTable { PublicKey = publicKey })
                .Property<long>(nameof(DelegatedPrimaryKeyGenerationTable.AutoGeneratedPrimaryKey));

            var temporarilyGeneratedPrimaryKey = generatedPrivateKeyEntry.CurrentValue;
            if (temporarilyGeneratedPrimaryKey >= 0) throw new ApplicationException("emporarilyGeneratedPrimaryKey >= 0");
            primaryKey.SetPrivateKey(temporarilyGeneratedPrimaryKey);
            if (!primaryKey.CheckExpectsAssignment()) throw new ApplicationException("!primaryKey.CheckExpectsAssignment()");

            return generatedPrivateKeyEntry;
        }

        public PropertyEntry<DelegatedPrimaryKeyGenerationTable, long>
            AttachExistingPrimaryKeyWithMissingRecordData<TRecordData, TQueryableRecordData>(
            PrimaryKey primaryKey)
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            if (primaryKey == null) throw new ArgumentNullException(nameof(primaryKey));
            if (primaryKey.CheckExpectsAssignment()) throw new ApplicationException("primaryKey.CheckExpectsAssignment()");
            EnsureLocked();

            long privateKey = primaryKey.PrivateKey ?? throw new ApplicationException("!primaryKey.PrivateKey.HasValue");

            var generatedPrivateKeyEntry = DelegatedPrimaryKeyGenerationTableSet<TRecordData, TQueryableRecordData>()
                .Attach(new DelegatedPrimaryKeyGenerationTable
                {
                    PublicKey = primaryKey.PublicKey ?? throw new ApplicationException("!primaryKey.PublicKey.HasValue"),
                    AutoGeneratedPrimaryKey = privateKey
                })
                .Property<long>(nameof(DelegatedPrimaryKeyGenerationTable.AutoGeneratedPrimaryKey));

            if (generatedPrivateKeyEntry.CurrentValue != privateKey) throw new ApplicationException("generatedPrivateKeyEntry.CurrentValue != privateKey");
            return generatedPrivateKeyEntry;
        }

        public Task<List<RecordDataQueries.PrimaryKeyWithExists>> GetPrimaryKeys<TRecordData, TQueryableRecordData>(
            IEnumerable<Guid> publicKeys, CancellationToken cancellationToken)
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            if (publicKeys == null) throw new ArgumentNullException(nameof(publicKeys));
            EnsureLocked();
            return DelegatedPrimaryKeyGenerationTableSet<TRecordData, TQueryableRecordData>()
                .Where(primaryKey => publicKeys.Contains(primaryKey.PublicKey))
                .GroupJoin(
                    Set<TQueryableRecordData>(),
                    primaryKey => primaryKey.AutoGeneratedPrimaryKey,
                    entity => EF.Property<long>(entity, MetadataHelper.RecordDataNeverGeneratedBigintPrimaryKeyIdPropertyName),
                    (primaryKey, singleEntityGroup) => new { PrimaryKey = primaryKey, SingleEntityGroup = singleEntityGroup })
                .SelectMany(
                    g => g.SingleEntityGroup.DefaultIfEmpty(),
                    (g, entity) => new
                    {
                        g.PrimaryKey,
                        Entity = entity
                    })
                .AsNoTracking()
                .Select(x => new RecordDataQueries.PrimaryKeyWithExists
                {
                    PublicKey = x.PrimaryKey.PublicKey,
                    PrivateKey = x.PrimaryKey.AutoGeneratedPrimaryKey,
                    RecordDataExists = x.Entity != null
                })
                .ToListAsync(cancellationToken);
        }

