        public async Task<Dictionary<long, RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>>>
            GetPrimaryKeysWithRecordDataToDictionary<TRecordData, TQueryableRecordData>(
                IReadOnlyList<long> privateKeys,
                bool lockAndTrack,
                CancellationToken cancellationToken)
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            if (privateKeys == null) throw new ArgumentNullException(nameof(privateKeys));
            EnsureLocked();

            IQueryable<TQueryableRecordData> queryable = Set<TQueryableRecordData>();
            PessimisticLockingUpdateInterceptionContext lockContext = null;

            if (lockAndTrack)
            {
                if (Database.CurrentTransaction == null) throw new ApplicationException("lockAndTrack && Database.CurrentTransaction == null");
                var lastModifiedAtColumnName = GetLastModifiedAtColumnName(typeof(TRecordData));
                lockContext = StartPessimisticLockingInterception(
                    typeof(TQueryableRecordData), privateKeys, lastModifiedAtColumnName);
            }
            else
            {
                queryable = queryable.AsNoTracking();
            }

            try
            {
                queryable = lockContext?.Intercept(queryable) ?? queryable;
                return await GetPrimaryKeysWithRecordDataToDictionary<TRecordData, TQueryableRecordData>(
                    privateKeys, queryable, cancellationToken);
            }
            finally
            {
                lockContext?.Dispose();
            }
        }

        public Task<Dictionary<long, RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>>>
            GetPrimaryKeysWithRecordDataToDictionary<TRecordData, TQueryableRecordData>(
                IReadOnlyList<long> privateKeys, IQueryable<TQueryableRecordData> queryable, CancellationToken cancellationToken)
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            if (privateKeys == null) throw new ArgumentNullException(nameof(privateKeys));
            if (queryable == null) throw new ArgumentNullException(nameof(queryable));
            EnsureLocked();
            return queryable.Join(
                DelegatedPrimaryKeyGenerationTableSet<TRecordData, TQueryableRecordData>(),
                entity => EF.Property<long>(entity, MetadataHelper.RecordDataNeverGeneratedBigintPrimaryKeyIdPropertyName),
                primaryKey => primaryKey.AutoGeneratedPrimaryKey,
                (entity, primaryKey) => new RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>
                {
                    PublicKey = primaryKey.PublicKey,
                    PrivateKey = primaryKey.AutoGeneratedPrimaryKey,
                    RecordData = entity
                })
                .Where(p => privateKeys.Contains(p.PrivateKey))
                .ToDictionaryAsync(p => p.PrivateKey, cancellationToken);
        }

        public Dictionary<long, RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>>
            GetPrimaryKeysWithLocalRecordDataToDictionary<TRecordData, TQueryableRecordData>(
                IReadOnlyList<long> privateKeys)
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            if (privateKeys == null) throw new ArgumentNullException(nameof(privateKeys));
            EnsureLocked();

            var query = Set<TQueryableRecordData>().Local.Join(
                DelegatedPrimaryKeyGenerationTableSet<TRecordData, TQueryableRecordData>().Local,
                entity => EF.Property<long>(entity, MetadataHelper.RecordDataNeverGeneratedBigintPrimaryKeyIdPropertyName),
                primaryKey => primaryKey.AutoGeneratedPrimaryKey,
                (entity, primaryKey) => new RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>
                {
                    PublicKey = primaryKey.PublicKey,
                    PrivateKey = primaryKey.AutoGeneratedPrimaryKey,
                    RecordData = entity
                })
                .Where(p => privateKeys.Contains(p.PrivateKey));

            Dictionary<long, RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>> result = null;

            foreach (var record in query)
            {
                result ??= new Dictionary<long, RecordDataQueries.PrimaryKeyWithRecordData<TQueryableRecordData>>();
                result.Add(record.PrivateKey, record);
            }

            return result;
        }

        public DbSet<DelegatedPrimaryKeyGenerationTable>
            DelegatedPrimaryKeyGenerationTableSet<TRecordData, TQueryableRecordData>()
            where TRecordData : class
            where TQueryableRecordData : class, TRecordData
        {
            var queryableRecordDataType = GetQueryableRecordDataType(typeof(TRecordData));
            if (queryableRecordDataType != typeof(TQueryableRecordData)) throw new ApplicationException("queryableRecordDataType != typeof(TQueryableRecordData)");
            string tableName = Model.FindEntityType(queryableRecordDataType)?.GetTableName() ?? throw new ApplicationException("tableName == null");
            return Set<DelegatedPrimaryKeyGenerationTable>(
                name: tableName + DelegatedPrimaryKeyGenerationTable.EntityTableNameSuffix);
        }

