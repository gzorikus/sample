                    _afterAlternateSorting = beforeRead._afterAlternateSorting;
                    _withoutExtraValues = beforeRead._withoutExtraValues;
                    FilterBeforeRead = null;
                    ReadOnlyRecordsIncluded = beforeRead.ReadOnlyRecordsIncluded;
                    ReadRecordsCount = readRecordsCount;
                }

                private ReadIdentity(IReadIdentity<PrimaryKey> afterSortingByIds, bool readOnlyRecordsIncluded) : this()
                {
                    _afterSortingByIds = afterSortingByIds;
                    ReadOnlyRecordsIncluded = afterSortingByIds != null && readOnlyRecordsIncluded;
                }

                private ReadIdentity(
                    IReadIdentity<PrimaryKey.AfterAlternateSorting> afterAlternateSorting,
                    bool readOnlyRecordsIncluded,
                    IFilterBeforeRead filterBeforeRead)
                    : this()
                {
                    if (afterAlternateSorting == null && filterBeforeRead != null) throw new ApplicationException("afterAlternateSorting == null && filterBeforeRead != null");
                    _afterAlternateSorting = afterAlternateSorting;
                    ReadOnlyRecordsIncluded = afterAlternateSorting != null && readOnlyRecordsIncluded;
                    FilterBeforeRead = filterBeforeRead;
