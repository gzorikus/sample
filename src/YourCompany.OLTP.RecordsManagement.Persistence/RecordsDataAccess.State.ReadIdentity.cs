                    if (_withoutExtraValues != null)
                        return _withoutExtraValues.GetReadRecordIdentity(recordIndex, originalIdentityWhenSpecified);

                    throw new ApplicationException("_afterSortingByIds == null && _afterAlternateSorting == null && _withoutExtraValues == null");
                }

